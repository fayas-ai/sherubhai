export function getDistrictAt(x: number, z: number): string {
  if (z < -104) return 'Kerala International Airport';
  if (z > 98) return 'Marine Drive Beach';
  if (z < -68) return 'North InfoPark Strip';
  if (x < -104) return 'Far West Turf Blvd';
  if (x > 104) return 'East Harbourfront';
  if (z > 64) return 'South Coastal Blvd';
  if (x < -74) return 'West Cinema Strip';
  if (x > 74) return 'East Promenade';
  if (x > 46 && z < -28) return 'Hospital Square';
  if (x > 40 && z > 28) return 'Lagoon Resort';
  if (z < -30 && Math.abs(x) < 22) return 'Financial Square';
  if (z < -30 && x >= 22) return 'Uptown Plaza';
  if (z < -30 && x <= -22) return 'Market Yard';
  if (x < -52) return 'Rescue & Grove';
  if (x < -24 && z >= 6) return 'Highway Strip';
  if (x < -24 && z < 6) return 'Sweet Street';
  if (x > 24 && z >= 6) return 'Hotel Boulevard';
  if (x > 24 && z < 6) return 'Spice Avenue';
  if (z > 28) return 'Palm Colony';
  return 'Main Junction';
}
