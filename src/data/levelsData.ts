function resolveTargetCoords(spec: RawLevelSpec): Vec2 | undefined {
  if (!spec.targetId) return undefined;
  const b = BUILDINGS.find((x) => x.id === spec.targetId);
  if (b) return { x: b.x, z: b.z };
  const n = NPCS.find((x) => x.id === spec.targetId);
  if (n) return { x: n.x, z: n.z };
  const p = EMPTY_PLOTS.find((x) => x.id === spec.targetId);
  if (p) return { x: p.x, z: p.z };
  const v = VEHICLES.find((x) => x.id === spec.targetId);
  if (v) return { x: v.x, z: v.z };
  const c = WORLD_COLLECTIBLES.find((x) => x.id === spec.targetId);
  if (c) return { x: c.x, z: c.z };
  return undefined;
}

export const LEVELS: LevelDefinition[] = RAW_LEVELS.map((spec) => {
  const chapter = Math.ceil(spec.id / 10);
  const line = LEVEL_COMPLETION_LINES[(spec.id - 1) % LEVEL_COMPLETION_LINES.length];
  return {
    id: spec.id,
    chapter,
    chapterName: CHAPTER_NAMES[chapter],
    title: spec.title,
    story: spec.story,
    objectiveText: spec.objectiveText,
    objectiveType: spec.objectiveType,
    targetId: spec.targetId,
    targetCount: spec.targetCount,
    rewardGhop: spec.rewardGhop,
    rewardReputation: 25 + chapter * 10,
    rewardItem: spec.rewardItemName
      ? {
          id: `lvl_reward_${spec.id}`,
          name: spec.rewardItemName,
          mlName: spec.rewardItemMl ?? spec.rewardItemName,
          category: 'collectible',
          description: `Unlocked by completing Level ${spec.id}: ${spec.title}.`,
        }
      : undefined,
    completionLineMl: line.ml,
    completionLineEn: line.en,
    targetCoords: resolveTargetCoords(spec),
  };
});

export function getLevelById(id: number): LevelDefinition {
  return LEVELS.find((l) => l.id === id) ?? LEVELS[0];
}
